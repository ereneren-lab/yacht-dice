let changed = 0, skipped = 0;
for (const game of Object.keys(T)) {
  const file = path.join(DIR, game + '.html');
  if (!fs.existsSync(file)) { console.log('✗ ' + game + '.html 없음'); continue; }
  let html = fs.readFileSync(file, 'utf8');

  if (html.includes('tutorial.js')) { console.log('= [' + game + '] 이미 붙어 있음'); skipped++; continue; }
  if (!html.includes('</title>')) { console.log('✗ [' + game + '] </title>를 못 찾음'); continue; }

  const steps = JSON.stringify(T[game], null, 0);
  const inject =
    '</title>\n' +
    '<!-- 공용 튜토리얼 — ⚠️ </title> 직후여야 한다(뒤쪽 analytics.js는 주석 블록 안이라 그 뒤에 넣으면 갇힌다) -->\n' +
    '<script src="tutorial.js"></script>\n' +
    '<script>try{TUT.init({game:' + JSON.stringify(game) + ',steps:' + steps + '})}catch(e){}</script>';

  html = html.replace('</title>', inject);
  fs.writeFileSync(file, html);
  console.log('✓ [' + game + '] 튜토리얼 ' + T[game].length + '단계 삽입');
  changed++;
}
console.log('\n삽입 ' + changed + '개 · 건너뜀 ' + skipped + '개');
